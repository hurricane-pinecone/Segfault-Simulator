#pragma once

#include "engine/core/ecs/entity.h"

#include <cstdint>
#include <string>
#include <string_view>
#include <vector>

namespace sfs::reflect
{

/** The value types a reflected field can hold. */
enum class FieldKind : uint8_t
{
  Bool,
  Int,  // int / int32_t
  UInt, // unsigned / uint32_t
  Float,
  String, // std::string
  Vec2,   // glm::vec2
  Vec3,   // glm::vec3
  Vec4,   // glm::vec4
  Quat,   // glm::quat
  Mesh,   // MeshHandle (saved by mesh name)
  Json,   // nlohmann::json: free-form data, saved as-is; not edited directly
  StringList, // std::vector<std::string>
  AssetRef,   // sfs::AssetRef<T>: a scriptable object of type T (saved as
              // "asset:<id>"; see scriptableObject.h)
};

/** Editor hints for a field, from its [[sfs::...]] attributes. */
struct FieldAttributes
{
  bool color = false;  // [[sfs::color]]: edit a vec3/vec4 as a colour
  bool script = false; // [[sfs::script]]: a string naming a game object script
  bool texture =
      false; // [[sfs::texture]]: a string naming a texture ("asset:<id>")
  bool materials =
      false; // [[sfs::materials]]: a string list of a mesh's material slots
  bool material = false; // [[sfs::material]]: a string naming a material
                         // asset ("asset:<id>")
  // [[sfs::emissionLight]]: a setting of the light the component's glowing
  // materials give off; the editor shows it only while one of them can glow
  bool emissionLight = false;
  // [[sfs::showIf(field)]]: the editor shows it only while that bool field
  // (of the same object) is on, e.g. a camera's bloom settings while it
  // blooms; "!field": only while it's off
  std::string showIf;
  bool hasRange = false; // [[sfs::range(min, max)]]
  std::string assetType; // AssetRef: the scriptable object type it refers to,
                         // e.g. "ItemDef"
  float min = 0.0f;
  float max = 0.0f;
};

/** One reflected field of a type. */
struct FieldInfo
{
  std::string name;        // as declared, e.g. "castsShadow"
  std::string displayName; // for the editor, e.g. "Casts Shadow"
  FieldKind kind = FieldKind::Float;
  FieldAttributes attributes;

  // The field's address inside an object of the owning type.
  void* (*address)(void* object) = nullptr;

  template <typename T>
  T& in(void* object) const
  {
    return *static_cast<T*>(address(object));
  }
};

/** What a reflected type is, which decides how the editor uses it. */
enum class TypeKind : uint8_t
{
  Component,
  System,
  GameObject,
  MeshSource,       // provides procedural meshes (sfs::MeshSource)
  ScriptableObject, // shared data in an .asset file (sfs::ScriptableObject)
};

/** Type-erased access to component T on an entity. */
struct ComponentOps
{
  bool (*has)(const Entity& entity) = nullptr;
  void* (*get)(const Entity& entity) = nullptr; // nullptr if absent
  void (*add)(const Entity& entity) = nullptr;  // default-constructed
  void (*remove)(const Entity& entity) = nullptr;
};

/** Making and freeing objects of a scriptable object type
 * (sfs::ScriptableObject). */
struct ScriptableOps
{
  void* (*create)() =
      nullptr; // a new, default object, as an sfs::ScriptableObject*
  void (*destroy)(void* object) = nullptr;
};

/** A reflected type: its names, kind, fields and (for components) ops. */
struct TypeInfo
{
  std::string name;        // C++ name, e.g. "Transform3DComponent"
  std::string displayName; // for the editor, e.g. "Transform3D"
  std::string module;      // which module registered it (e.g. "engine")
  TypeKind kind = TypeKind::Component;
  std::vector<FieldInfo> fields;
  ComponentOps component;   // valid when kind == Component
  ScriptableOps scriptable; // valid when kind == Data
};

/**
 * Every reflected type, from the engine and from any game module. One instance
 * per process (it lives in engine-core), so a module loaded at runtime
 * registers into the same registry the editor reads.
 */
class TypeRegistry
{
public:
  /** Add a type (replacing any with the same name). */
  void add(TypeInfo type);

  /** Drop every type a module registered, e.g. before unloading it. */
  void removeModule(std::string_view module);

  const TypeInfo* find(std::string_view name) const;

  const std::vector<TypeInfo>& types() const { return m_types; }

private:
  std::vector<TypeInfo> m_types;
};

/**
 * The process-wide registry, with the engine's own types already registered.
 */
TypeRegistry& types();

/**
 * Registers the engine's components. Generated by sfs-codegen from the
 * engine's component headers; called by types() on first use.
 */
void registerEngineTypes(TypeRegistry& registry);

} // namespace sfs::reflect
